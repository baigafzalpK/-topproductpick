// Regenerates manifest, index, sitemap and category counts from src/data/pages.
// Safe to re-run. Runs automatically before dev/build.
import fs from "node:fs";
import path from "node:path";

const DATA = path.join(process.cwd(), "src", "data");
const PAGES = path.join(DATA, "pages");
const read = (f) => JSON.parse(fs.readFileSync(path.join(DATA, f), "utf8"));
const write = (f, v) => fs.writeFileSync(path.join(DATA, f), JSON.stringify(v, null, 2) + "\n");

const PRIORITY = { department: 0.9, category: 0.9, roundup: 0.8, review: 0.7, comparison: 0.7, "buying-guide": 0.7, howto: 0.6, troubleshoot: 0.6, page: 0.3 };

const pages = fs
  .readdirSync(PAGES)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) => ({ slug: f.replace(/\.json$/, ""), ...JSON.parse(fs.readFileSync(path.join(PAGES, f), "utf8")) }));

const errors = [];
for (const p of pages) {
  for (const k of ["type", "title", "h1", "metaDescription", "lede", "updatedAt", "data"]) if (!p[k]) errors.push(`${p.slug}: missing "${k}"`);
  const text = JSON.stringify(p).toLowerCase();
  for (const banned of ["we tested", "hands-on", "our lab", "in our testing"]) if (text.includes(banned)) errors.push(`${p.slug}: contains "${banned}" (editorial rule)`);
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const slugs = new Set(pages.map((p) => p.slug));
write("manifest.json", { slugs: pages.map((p) => p.slug) });
write("index.json", Object.fromEntries(pages.map((p) => [p.slug, { title: p.h1, type: p.type }])));

// The search index is generated by src/app/search-index.json/route.ts at build time.

write(
  "sitemap.json",
  [{ slug: "", updatedAt: pages.map((p) => p.updatedAt).sort().at(-1), priority: 1 }, { slug: "categories", updatedAt: pages.map((p) => p.updatedAt).sort().at(-1), priority: 0.6 }].concat(
    pages.map((p) => ({ slug: p.slug, updatedAt: p.updatedAt, priority: PRIORITY[p.type] ?? 0.5 }))
  )
);

const categories = read("categories.json").map((c) => ({ ...c, count: pages.filter((p) => p.category === c.slug).length }));
for (const c of categories) if (!slugs.has(c.slug)) console.warn(`warning: categories.json lists "${c.slug}" but no page exists`);
write("categories.json", categories);

console.log(`index built: ${pages.length} pages`);
